import math

def round_up(x):
    #Округлює похибку з надлишком до однієї значущої цифри
    exp = math.floor(math.log10(x))          # порядок першої значущої цифри
    mant = math.ceil(x / 10 ** exp - 1e-9)   # першу цифру округлюємо вгору
    return mant * 10 ** exp                  # повертаємо число до його порядку


# Завдання а) яка рівність точніша
print("Завдання а)")
a_approx = 0.095                 # наближене значення 2/21
b_approx = 4.69                  # наближене значення sqrt(22)
a_exact = 2 / 21                 # значення 2/21 з великою кількістю знаків
b_exact = math.sqrt(22)          # значення sqrt(22) з великою кількістю знаків
print(f"  a = 2/21     = {a_exact:.7f}...,  наближення {a_approx}")
print(f"  b = sqrt(22) = {b_exact:.7f}...,  наближення {b_approx}")

abs_a = round_up(abs(a_exact - a_approx))   # гранична абсолютна похибка a
abs_b = round_up(abs(b_exact - b_approx))   # гранична абсолютна похибка b
print(f"  |a_точне - a| = {abs(a_exact - a_approx):.2e}  <=  {abs_a:.4f}")
print(f"  |b_точне - b| = {abs(b_exact - b_approx):.2e}  <=  {abs_b:.4f}")

rel_a = abs_a / abs(a_approx)    # гранична відносна похибка a
rel_b = abs_b / abs(b_approx)    # гранична відносна похибка b
print(f"  відносна похибка a: {rel_a:.2e} = {rel_a * 100:.3f} %")
print(f"  відносна похибка b: {rel_b:.2e} = {rel_b * 100:.3f} %")

if rel_a < rel_b:                # точніша та рівність, де відносна похибка менша
    print("  Висновок: точніша рівність 2/21 = 0,095")
else:
    print("  Висновок: точніша рівність sqrt(22) = 4,69")

# Завдання б) округлення сумнівних цифр
print("\nЗавдання б)")
c = 24.5641                      # наближене число
delta_c = 0.09 / 100             # відносна похибка 0,09 % у частках одиниці
abs_c = c * delta_c              # абсолютна похибка числа: c * delta
print(f"  c = {c}, відносна похибка = {delta_c * 100:.2f} %")
print(f"  абсолютна похибка c: {abs_c:.5f}")

k = math.floor(-math.log10(abs_c))   # к-сть десяткових знаків: похибка < 10^(-k)
print(f"  {abs_c:.5f} < {10 ** -k}  =>  правильні цифри до {k}-го знака після коми")

c_rounded = round(c, k)              # відкидаємо сумнівні цифри округленням
round_err = abs(c - c_rounded)       # похибка самого округлення
total_err = abs_c + round_err        # абсолютна похибка результату
print(f"  округлене число: {c_rounded}")
print(f"  похибка округлення: {round_err:.4f}")
print(f"  абсолютна похибка результату: {abs_c:.4f} + {round_err:.4f} = {total_err:.4f}")

# Завдання в) похибки числа з правильними цифрами
print("\nЗавдання в)")
f_str = "4.478"                           # число як рядок, щоб порахувати знаки
f = float(f_str)                          # те саме число як дійсне
decimals = len(f_str.split(".")[1])       # кількість знаків після коми
abs_f = 10 ** -decimals                   # одиниця останнього розряду
rel_f = abs_f / abs(f)                    # гранична відносна похибка
print(f"  f = {f}, усі цифри правильні")
print(f"  гранична абсолютна похибка: {abs_f}")
print(f"  гранична відносна похибка: {abs_f} / {f} = {rel_f:.2e} = {rel_f * 100:.3f} %")